"""
1. 稀疏向量索引：SPARSE_INVERTED_INDEX（倒排索引）

【原理】
稀疏向量的特点：维度极高（如250,000维），但绝大多数元素为0（非零元素<1%）

示例稀疏向量（词汇表10000维）：
文档1: {88: 0.5, 666: 0.8, 999: 1.2}  # 只有3个非零值
文档2: {88: 0.3, 123: 0.9}            # 只有2个非零值
文档3: {666: 0.7, 999: 0.5, 5000: 0.4}

【倒排索引结构】
类似搜索引擎的倒排索引，只存储非零维度：

维度88  -> [文档1(0.5), 文档2(0.3)]
维度123 -> [文档2(0.9)]
维度666 -> [文档1(0.8), 文档3(0.7)]
维度999 -> [文档1(1.2), 文档3(0.5)]
维度5000-> [文档3(0.4)]

【查询过程】
查询向量: {88: 0.6, 999: 1.0}

步骤1：查找维度88 -> 找到文档1和文档2
步骤2：查找维度999 -> 找到文档1和文档3
步骤3：合并结果，计算得分
  - 文档1出现在两个维度中，得分高
  - 文档2和文档3各出现一次

【优势】
✅ 极快速度：只查询非零维度，跳过大量零值
✅ 精确匹配：完全保留原始得分，无精度损失
✅ 省空间：只存储非零元素

【Milvus配置】
"""
