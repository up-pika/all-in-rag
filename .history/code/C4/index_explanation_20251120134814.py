def create_hybrid_index_example():
    """
    完整的混合检索索引创建示例
    """
    from pymilvus import (
        connections,
        Collection,
        CollectionSchema,
        FieldSchema,
        DataType
    )
    
    # 1. 定义Schema
    fields = [
        FieldSchema(name="id", dtype=DataType.INT64, is_primary=True, auto_id=True),
        FieldSchema(name="text", dtype=DataType.VARCHAR, max_length=1000),
        
        # 稀疏向量字段（BM25/TF-IDF）
        FieldSchema(name="sparse_vector", dtype=DataType.SPARSE_FLOAT_VECTOR),
        
        # 密集向量字段（BGE/BERT）
        FieldSchema(name="dense_vector", dtype=DataType.FLOAT_VECTOR, dim=768)
    ]
    
    schema = CollectionSchema(fields, description="混合检索示例")
    collection = Collection("hybrid_demo", schema)
    
    # 2. 创建稀疏向量索引（倒排索引）
    sparse_index = {
        "index_type": "SPARSE_INVERTED_INDEX",
        "metric_type": "IP"
    }
    collection.create_index("sparse_vector", sparse_index)
    print("✅ 稀疏向量索引创建成功（倒排索引）")
    
    # 3. 创建密集向量索引（自动选择）
    dense_index = {
        "index_type": "AUTOINDEX",
        "metric_type": "IP"
    }
    collection.create_index("dense_vector", dense_index)
    print("✅ 密集向量索引创建成功（自动索引）")
    
    # 4. 加载到内存（必须！）
    collection.load()
    print("✅ Collection加载到内存，可以开始搜索")
    
    # 5. 搜索时的使用
    search_params = {
        "metric_type": "IP",  # 使用与索引相同的度量
        "params": {}          # AUTOINDEX不需要额外参数
    }
    
    # 对于IVF类型，需要指定nprobe
    search_params_ivf = {
        "metric_type": "IP",
        "params": {"nprobe": 10}  # 搜索10个最近的簇
    }
    
    return collection

