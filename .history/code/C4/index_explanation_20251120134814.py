# ============================================================================
# 第四部分：度量类型（Metric Type）
# ============================================================================

"""
度量类型（Metric Type）：定义如何计算向量相似度

常见度量类型：

1️⃣ IP (Inner Product) - 内积
   公式：similarity = Σ(a[i] * b[i])
   
   计算示例：
   vec1 = [1, 2, 3]
   vec2 = [4, 5, 6]
   IP = 1*4 + 2*5 + 3*6 = 4 + 10 + 18 = 32
   
   ✅ 适合归一化后的向量（如BGE模型输出）
   ✅ 得分越高越相似
   ⚠️  需要向量已归一化，否则长度会影响结果

2️⃣ COSINE - 余弦相似度
   公式：similarity = (A·B) / (||A|| * ||B||)
   
   计算示例：
   vec1 = [1, 2, 3]
   vec2 = [4, 5, 6]
   COSINE = 32 / (√14 * √77) ≈ 0.974
   
   ✅ 不受向量长度影响
   ✅ 适合未归一化的向量
   ✅ 结果范围[-1, 1]，1表示完全相同

3️⃣ L2 - 欧氏距离
   公式：distance = √(Σ(a[i] - b[i])²)
   
   ✅ 几何意义直观
   ⚠️  得分越低越相似（距离越近）
   
选择建议：
- BGE、Sentence-BERT等模型 -> IP（已归一化）
- 自己训练的未归一化模型 -> COSINE
- 地理坐标、物理空间 -> L2
"""

