"""
❓ Q1: 为什么稀疏向量用倒排索引，密集向量用HNSW/IVF？

A: 因为数据特性不同：
- 稀疏向量：高维稀疏，倒排索引天然适合（只索引非零维度）
- 密集向量：低维稠密，需要空间划分算法（聚类或图）

❓ Q2: 创建索引后必须load()吗？

A: 是的！
collection.create_index()  # 只是创建索引结构（存储在磁盘）
collection.load()          # 加载到内存，才能搜索

❓ Q3: 可以更换索引类型吗？

A: 可以，但需要先删除旧索引：
collection.drop_index()
collection.create_index("field_name", new_index_config)
collection.load()

❓ Q4: IP和COSINE有什么区别？

A: 如果向量已归一化（||v|| = 1），IP和COSINE完全等价
BGE等模型输出已归一化，所以用IP更快（少一次归一化计算）

❓ Q5: AUTOINDEX具体会选择什么索引？

A: 取决于数据量：
- <8192条：FLAT
- 8192-1000000条：IVF_FLAT
- >1000000条：HNSW

❓ Q6: 混合检索必须两个向量都创建索引吗？

A: 是的！每个向量字段都需要独立的索引，因为它们：
- 维度不同（稀疏250K维 vs 密集768维）
- 稀疏性不同（<1% vs 100%）
- 检索算法不同（倒排索引 vs 图/聚类）
"""

