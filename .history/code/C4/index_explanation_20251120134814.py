# 第三部分：密集向量索引 - AUTOINDEX
# ============================================================================

"""
2. 密集向量索引：AUTOINDEX（自动索引）

【原理】
密集向量的特点：维度较低（384-1536维），但所有维度都有值（非零率100%）

示例密集向量（768维）：
文档1: [0.23, -0.45, 0.67, ..., -0.12]  # 768个浮点数
文档2: [0.56, -0.23, 0.89, ..., 0.34]
文档3: [-0.12, 0.78, -0.34, ..., 0.56]

【AUTOINDEX】
Milvus会根据数据规模自动选择最优索引类型：

数据量小(<8192条)  -> FLAT（暴力搜索，精确）
数据量中(8K-1M)    -> IVF_FLAT（倒排文件索引）
数据量大(>1M)      -> HNSW（分层导航小世界图）

【常见密集向量索引类型】

1️⃣ FLAT（暴力搜索）
   原理：逐个计算查询向量与所有文档向量的相似度
   ✅ 100%精确
   ❌ 速度慢，不适合大规模数据
   
2️⃣ IVF_FLAT（倒排文件索引）
   原理：将向量空间划分为多个聚类（Voronoi单元）
   
   构建阶段：
   - 使用K-means将所有向量聚类为N个簇（如1024个）
   - 每个簇维护一个文档列表
   
   查询阶段：
   - 找到查询向量最近的nprobe个簇（如10个）
   - 只在这些簇中搜索，跳过其他簇
   - 大幅减少计算量（从100万降到1万）
   
   ✅ 速度快，适合百万级数据
   ⚠️  有小量精度损失（可能漏掉边界向量）
   
3️⃣ HNSW（分层导航小世界图）
   原理：构建多层图结构，类似"六度分离"理论
   
   图结构：
   - 顶层：稀疏连接，用于快速定位大致区域
   - 中层：中等密度连接
   - 底层：密集连接，精确搜索
   
   查询过程：
   - 从顶层开始，快速跳转到目标区域
   - 逐层下降，逐步精细化搜索
   - 在底层找到最终Top-K结果
   
   ✅ 查询速度极快
   ✅ 精度高（通常>95%）
   ⚠️  构建索引较慢
   💾 内存占用较大

【Milvus AUTOINDEX配置】
"""
