# ============================================================================
# 第一部分：索引基础概念
# ============================================================================

"""
索引（Index）是什么？
- 索引是一种数据结构，用于加速向量检索
- 类比：数据库的B树索引加速SQL查询，向量索引加速相似度搜索
- 目标：在百万、千万级向量中快速找到最相似的Top-K个结果

核心权衡：
✅ 速度提升：从O(N)降到O(log N)或更好
⚠️  精度损失：某些索引方法会牺牲少量精度换取速度
💾 空间占用：索引本身需要额外存储空间
"""

